#!/usr/bin/env python3
"""Generate src/grapheme-properties.h: the Unicode properties grapheme
clusters (mode 2027, src/grapheme.h) need. No network at build time.

Usage: update-grapheme-properties.py GraphemeBreakProperty.txt emoji-data.txt \\
                                     DerivedCoreProperties.txt > src/grapheme-properties.h
Sources: https://www.unicode.org/Public/<version>/ucd/auxiliary/GraphemeBreakProperty.txt
         https://www.unicode.org/Public/<version>/ucd/emoji/emoji-data.txt
         https://www.unicode.org/Public/<version>/ucd/DerivedCoreProperties.txt (InCB)
Unicode data license: doc/UNICODE-LICENSE.txt
"""
import hashlib
import re
import sys
from pathlib import Path

if len(sys.argv) != 4:
    sys.exit(__doc__)

GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
       "SpacingMark", "L", "V", "T", "LV", "LVT"]
INCB = ["None", "Linker", "Consonant", "Extend"]
EXTPICT, EMOJI = 0x40, 0x80

values = bytearray(0x110000)   # bits 0-3 GCB, 4-5 InCB, 6 ExtPict, 7 Emoji


def ranges(filename):
    for line in Path(filename).read_text(encoding="utf-8").splitlines():
        fields = [f.strip() for f in line.split("#", 1)[0].split(";")]
        if len(fields) < 2 or not fields[0]:
            continue
        limits = fields[0].split("..")
        yield int(limits[0], 16), int(limits[-1], 16), fields[1:]


for first, last, (prop, *_) in ranges(sys.argv[1]):
    for c in range(first, last + 1):
        values[c] = (values[c] & ~0x0F) | GCB.index(prop)

for first, last, (prop, *_) in ranges(sys.argv[2]):
    bit = {"Extended_Pictographic": EXTPICT, "Emoji": EMOJI}.get(prop)
    if bit:
        for c in range(first, last + 1):
            values[c] |= bit

for first, last, fields in ranges(sys.argv[3]):
    if fields[0] == "InCB" and len(fields) > 1:
        for c in range(first, last + 1):
            values[c] = (values[c] & ~0x30) | INCB.index(fields[1]) << 4


def version(filename):
    head = Path(filename).read_text(encoding="utf-8")[:600]
    m = re.search(r"-(\d+\.\d+\.\d+)\.txt|Unicode (\d+\.\d+\.\d+)|# Version: (\d+\.\d+)", head)
    return next(g for g in m.groups() if g) if m else "?"


print("/* Generated by tools/update-grapheme-properties.py. Do not edit by hand.")
for filename in sys.argv[1:]:
    p = Path(filename)
    print(" * %s (Unicode %s) SHA256 %s" % (p.name, version(filename), hashlib.sha256(p.read_bytes()).hexdigest()))
print(" * Unicode license: doc/UNICODE-LICENSE.txt. */")
print("#ifndef RXVT_GRAPHEME_PROPERTIES_H\n#define RXVT_GRAPHEME_PROPERTIES_H\n#include <stdint.h>\n")
print("enum grapheme_break\n{")
print(",\n".join("  GCB_%s" % name for name in GCB))
print("};\n")
print("enum indic_conjunct_break\n{")
print(",\n".join("  INCB_%s" % name for name in INCB))
print("};\n")
print("#define GRAPHEME_GCB(p)     ((p) & 0x0f)\n#define GRAPHEME_INCB(p)    ((p) >> 4 & 3)")
print("#define GRAPHEME_EXTPICT    0x40\n#define GRAPHEME_EMOJI      0x80\n")
print("static const struct { uint32_t first; uint32_t last : 24, props : 8; } grapheme_ranges[] = {")
first = 0
for end in range(1, len(values) + 1):
    if end == len(values) or values[end] != values[first]:
        if values[first]:
            print("  { 0x%x, 0x%x, 0x%02x }," % (first, end - 1, values[first]))
        first = end
print("};\n")
print("""// the properties of c: GCB, InCB and the two flags
static inline unsigned int
grapheme_properties (uint32_t c)
{
  if (c < 0x20)
    return c == '\\r' ? GCB_CR : c == '\\n' ? GCB_LF : GCB_Control;
  if (c < 0x7f) // Other; the keycap bases are Emoji too
    return (c >= '0' && c <= '9') || c == '#' || c == '*' ? GRAPHEME_EMOJI : 0;

  unsigned int lo = 0, hi = sizeof grapheme_ranges / sizeof *grapheme_ranges;
  while (lo < hi)
    {
      unsigned int mid = lo + (hi - lo) / 2;
      if (c < grapheme_ranges[mid].first) hi = mid;
      else if (c > grapheme_ranges[mid].last) lo = mid + 1;
      else return grapheme_ranges[mid].props;
    }
  return 0;
}
#endif""")
